## Calculates the text´s bonus based on letter frequencies(same as in), amount of spaces(acceptable from 15% to 30%, after that, an penalty based on how far the space frequency is from the goal) and repetition of characters( based on how many times a character appears in a row, removing points after 3 times in a row); the penalty works like the following: each "penalty score" is initially set to its max (the score´s weight * 10) and based on the text, the score is penalized
def bonus_score(text=str):
    space_amount_score = 10 * SPACE_AMOUNT_WEIGHT
    repetition_score = 10 * REPETITION_WEIGHT
    frequency_score = 0

    ### Sets space amount score
    if ((0.15 * len(text)) > text.count(" ")) or (text.count(" ") > (0.3 * len(text))):
        try:
            space_amount_score *= min((text.count(" ") / 0.15 * len(text)), ((-text.count(" ")) / (0.7 * len(text))) + (1/0.7))
        except ZeroDivisionError:
            space_amount_score = 0

    ### Sets repetition score
    for char in list(VOCABULARY.keys()):
        if char == " ":
            continue
        if char not in text:
            continue
        i = 0
        for letter in text:
            if repetition_score <= 0:
                repetition_score = 0
                break
            if char == letter:
                i += 1
            else:
                if i <= 2:
                    i = 0
                else:
                    repetition_score -= 10 * REPETITION_WEIGHT * (0.025 * (i - 2))
                    i = 0

    ### Sets letter frequency score
    letter_frequency = 0
    for char in text:
        if char not in list("abcdefghijklmnopqrstuvwxyz"):
            text.replace(char, " ")
    for letter, frequency in LETTER_FREQUENCIES.items():
        try:
            letter_frequency = text.count(letter) / len(text)
        except ZeroDivisionError:
            letter_frequency = 0
        try:
            frequency_score += min(letter_frequency/frequency, (-letter_frequency / (len(text) - frequency)) + (len(text) / (len(text) - frequency))) / len(LETTER_FREQUENCIES)
        except ZeroDivisionError:
            frequency_score += 0
    frequency_score *= 10 * LETTER_FREQUENCY_WEIGHT
    return space_amount_score + repetition_score + frequency_score

## Checks if score is invalid or "parameters"(a custom command to show the weights and biases of the best scored NN)
def parse_score(user_score):
    if user_score == "" or user_score == None:
        return 0.0
    if isinstance(user_score, str):
        cleaned = user_score.strip().lower()
        if cleaned == "parameters":
            return "parameters"
        try:
            return float(cleaned)
        except (TypeError, ValueError):
            return 0.0
    try:
        return float(user_score)
    except (TypeError, ValueError, OverflowError):
        return 0.0

